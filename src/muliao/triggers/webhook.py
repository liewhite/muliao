"""webhook 触发：外部系统带 token 调用 POST /api/hooks/{name}[?session_id=]。config = {}。

- token 是我们签发给外部系统的凭证，事实来源是触发器自己：state 里只存 SHA-256，明文只在生成时返回一次，
  且只能由用户在界面上生成（agent 创建的 webhook 在用户生成 token 之前收不到事件）。不放进 vault——vault
  存的是外部系统发给我们的凭证。
- 先鉴权再读请求体；触发器不存在、不是 webhook、没有 token、token 不匹配，都返回同一个 401，不暴露哪些名称存在。
- 不带 session_id 新建会话，响应返回会话 id；带上它的后续事件在同一会话里继续（只能续写本触发器发起的会话）。
"""

from __future__ import annotations

import hashlib
import hmac
import logging
import secrets
from typing import Any

from sqlalchemy import select

from muliao.db import Database
from muliao.errors import InvalidInput, Unauthorized
from muliao.models import Session, Trigger
from muliao.triggers.service import TriggerService

log = logging.getLogger(__name__)

KIND = "webhook"


def _hash(token: str) -> str:
    return hashlib.sha256(token.encode()).hexdigest()


def hook_url(public_url: str, name: str) -> str:
    return f"{public_url.rstrip('/')}/api/hooks/{name}"


class WebhookKind:
    name = KIND
    description = (
        "Fires when an external system POSTs to /api/hooks/<name> with a bearer token; the request body is the "
        "event. config: {}. The token can only be generated by the user in the app."
    )

    def __init__(self, public_url: str):
        self._public_url = public_url

    def configure(self, config: dict[str, Any]) -> tuple[dict[str, Any], dict[str, Any]]:
        if config:
            raise InvalidInput(f"webhook trigger config must be {{}}, got {config!r}")
        return {}, {}

    def status(self, trigger: Trigger) -> dict[str, Any]:
        return {"url": hook_url(self._public_url, trigger.name), "has_token": "token_hash" in trigger.state}


class Webhooks:
    """webhook 的激活机制：鉴权与 token 管理。"""

    def __init__(self, db: Database, triggers: TriggerService):
        self._db = db
        self._triggers = triggers

    async def authenticate(self, name: str, token: str) -> int:
        """校验 token，返回触发器 id。失败的各种原因返回同一个错误，且都要计算一次摘要。"""
        digest = _hash(token)
        async with self._db.transaction() as s:
            trigger = await s.scalar(select(Trigger).where(Trigger.name == name, Trigger.kind == KIND))
            stored = None if trigger is None else trigger.state.get("token_hash")
            if stored is None or not hmac.compare_digest(stored, digest):
                log.warning("webhook rejected: unknown trigger or wrong token", extra={"trigger": name})
                raise Unauthorized("unknown webhook or wrong token")
            return trigger.id

    async def deliver(self, trigger_id: int, payload: str, session_id: str | None) -> Session | None:
        """None 表示前置检查判定这次不触发。"""
        if not payload.strip():
            raise InvalidInput("event payload must not be empty")
        return await self._triggers.fire(trigger_id, payload, session_id)

    async def generate_token(self, trigger_id: int) -> str:
        """生成（或重新生成）token：旧 token 立即失效。只由用户在界面上调用。"""
        token = secrets.token_urlsafe(32)
        async with self._db.transaction() as s:
            trigger = await self._triggers.get_in(s, trigger_id)
            if trigger.kind != KIND:
                raise InvalidInput(f"trigger {trigger.name!r} is a {trigger.kind} trigger, not a webhook")
            self._triggers.set_state(trigger, token_hash=_hash(token))
        log.info("webhook token generated", extra={"trigger_id": trigger_id})
        return token
